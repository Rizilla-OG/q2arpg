#!/usr/bin/env python3
"""Generates q2rpg_psx_test.map: a test arena for the PSX-update monsters and trigger_safe_fall.

Not shipped. You start on a 1024-unit tower. Jump off its north half (arrow floor below) and a
trigger_safe_fall saves you; the south half has none, for comparison. On the floor: an Arachnid,
and a sleepy Guardian that wakes when you cross the middle of the arena.
Run:  python3 make_psx_test.py  (writes q2rpg_psx_test.map next to this script)
"""

import os

from make_tutorial import brush, entity

FLOOR = "e1u1/floor1_3"
WALL = "e1u1/wslt1_5"
PAD = "e1u1/arrowup0"
TRIGGER = "e1u1/trigger"

HALF = 1024     # arena spans -HALF..HALF in x and y
HEIGHT = 1280
TOWER_TOP = 1024
T = 16


def build():
    world = [
        brush(-HALF - T, -HALF - T, -T, HALF + T, HALF + T, 0, FLOOR),               # floor
        brush(-HALF - T, -HALF - T, HEIGHT, HALF + T, HALF + T, HEIGHT + T, WALL),   # ceiling
        brush(-HALF - T, -HALF - T, 0, -HALF, HALF + T, HEIGHT, WALL),               # west
        brush(HALF, -HALF - T, 0, HALF + T, HALF + T, HEIGHT, WALL),                 # east
        brush(-HALF, -HALF - T, 0, HALF, -HALF, HEIGHT, WALL),                       # south
        brush(-HALF, HALF, 0, HALF, HALF + T, HEIGHT, WALL),                         # north
        brush(-HALF, -512, 0, -768, 512, TOWER_TOP, WALL),                           # tower
        brush(-768, 64, 0, -640, 512, 2, PAD),                                       # landing marker (safe side)
    ]
    ents = [
        entity({"classname": "info_player_start", "origin": f"-896 0 {TOWER_TOP + 24}", "angle": "0"}),
        # in the air off the tower's north half: one free landing
        entity({"classname": "trigger_safe_fall"}, [brush(-768, 64, 128, -640, 512, TOWER_TOP - 64, TRIGGER)]),
        entity({"classname": "trigger_once", "target": "psx_guardian", "message": "The Guardian wakes up."},
               [brush(-128, -HALF, 0, 128, HALF, 128, TRIGGER)]),
        entity({"classname": "monster_arachnid", "origin": "512 -512 24", "angle": "180"}),
        entity({"classname": "monster_guardian", "origin": "640 512 70", "angle": "180", "spawnflags": "8",
                "targetname": "psx_guardian"}),
    ]
    for lx in (-640, 0, 640):
        for ly in (-640, 0, 640):
            ents.append(entity({"classname": "light", "origin": f"{lx} {ly} {HEIGHT - 64}", "light": "600"}))

    worldspawn = entity({
        "classname": "worldspawn",
        "message": "PSX monster test",
        "sky": "unit1_",
        "_minlight": "24",
        "loot_nochests": "1",
        "loot_nomodifier": "1",
        "loot_elite_chance": "0",     # elites swap attacks; test the stock behavior
    }, world)
    header = ("// Q2ARPG test map for the PSX-update monsters and trigger_safe_fall. Not shipped.\n"
              "// Generated by make_psx_test.py; edit that, not this file.\n")
    return header + worldspawn + "\n" + "\n".join(ents) + "\n"


if __name__ == "__main__":
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "q2rpg_psx_test.map")
    with open(out, "w") as f:
        f.write(build())
    print(f"wrote {out}")
